def build_design_prompt(
    title: str, author: str, lang: str = "ru", context: dict | None = None
) -> str:
    """Паспорт оформления книги: две палитры, пара шрифтов, символ-экслибрис.

    ⚠ Шрифты модель НЕ называет свободно: `title_font` и `body_font` объявлены
    как `Literal` в services/ai_schemas.py, список уезжает в схему инструмента,
    и несуществующее имя становится непредставимым. До этого модель выдала
    `Freight Text Pro` (коммерческая гарнитура, в Google Fonts её нет) у 19 книг,
    и шрифт молча откатывался на запасной — `<link>` ошибок не даёт.
    Добавляете шрифт в список — сначала проверьте, есть ли у него кириллица.
    """
    language = "русском" if lang == "ru" else "английском"
    return f"""Собери «паспорт атмосферы» для оформления карточки книги
«{title}» ({author}).

{format_context(context)}

Палитры две, обе в настроении книги: palette_dark — «вечерняя» (тёмный фон,
светлый текст) и palette_light — «дневная» (светлый фон, тёмный текст).
Это одна атмосфера в двух освещениях, а не два разных дизайна: родственными
должны быть И акцент, И фон. Контраст текста и фона — не ниже WCAG AA.

Не бери гамму по умолчанию. Замер по 201 паспорту показал, что без этого
требования светлый фон выходит тёплым у 92% книг («состаренная бумага»),
а тёмный уходит в синюю «ночь» у 67% — то есть оформление получается не про
эту книгу, а про книги вообще. Цвет должен быть выводим из мира книги: эпохи,
географии, материала, времени суток. Если не можешь объяснить, почему фон
именно такой, — значит взял клише, выбери другой.
Дополнительно нарисуй symbol_svg — минималистичный векторный символ-экслибрис книги:
один элемент <svg viewBox="0 0 100 100"> с простыми формами (path, circle, rect, line),
цвета только из палитры паспорта, без текста, без script/обработчиков/внешних ссылок
и без атрибута href.
В поле statement напиши 2–3 предложения на {language} языке: почему для этой книги
выбран именно такой символ — что он означает и как связан с сюжетом или настроением
(не пересказ книги и не описание атмосферы!)."""


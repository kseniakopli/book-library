# ⚠ КОНТЕКСТ КНИГИ (22.07) — важное дополнение.
# Функции промптов принимают ЧЕТВЁРТЫЙ аргумент `context` — словарь:
#   {
#     "description": "аннотация книги из Google Books (до 1200 символов)",
#     "genres": "Fiction, Contemporary",
#     "year": 2021,
#     "avoid": ["бефстроганов", "сельдь под шубой", ...],   # уже затасканное
#     "avoid_artists": ["Agnes Obel", "Portishead", ...],   # только для музыки
#   }
# Зачем: без аннотации модель для малоизвестных книг УГАДЫВАЕТ по названию —
# «Капля духов в открытую рану» превратилась у Claude в арабский Дубай, хотя
# книга о московском парфюмерном мире. А `avoid` борется с однообразием:
# генерации независимы, и модель не знает, что бефстроганов она советует
# в каждой русской книге.
#
# ⚠⚠ СОВМЕСТИМОСТЬ — И ЕЁ ЛОВУШКА.
# Если ваша функция принимает только (title, author, lang), всё продолжит
# работать: `_build_with_context` в services/ai.py ловит TypeError и зовёт
# билдер по старой сигнатуре. Но ловит он ЛЮБОЙ TypeError, в том числе
# случайный внутри вашего промпта, — и тогда генерация тихо уходит БЕЗ
# контекста и без единой записи в логе. Если кажется, что запреты не
# действуют, первым делом проверьте, доехали ли они:
#     python scripts/show_prompt.py --book=<id> --category=music
#
# ⚠ ОТРИЦАТЕЛЬНЫЕ ПРИМЕРЫ РАБОТАЮТ КАК ПОДСКАЗКА (замер 02.08).
# Перечисленное «не бери» модель запоминает как образец жанра и приносит
# обратно: «Spiegel im Spiegel» стояла в промпте примером заезженного —
# и приехала в свежую генерацию. Формулируйте ПРИЗНАК, а не список имён.
# Там, где нужен именно список, дублируйте его проверкой в коде: промпт
# задаёт направление, границы держит код (см. services/atmosphere.py).
#
# Хелпер ниже собирает контекст в текст; используйте его в своих промптах.


def format_context(context: dict | None) -> str:
    """Аннотация, жанры, год и «не повторяй это» — куском текста для промпта."""
    if not context:
        return ""
    parts = []
    if context.get("description"):
        parts.append(
            "Аннотация книги (опирайся на неё, не додумывай сюжет и географию):\n"
            f"{context['description']}"
        )
    meta = ", ".join(
        str(v) for v in (context.get("genres"), context.get("year")) if v
    )
    if meta:
        parts.append(f"Жанры и год: {meta}")
    if context.get("avoid"):
        parts.append(
            "Эти варианты уже примелькались в других книгах библиотеки — "
            "НЕ предлагай ни их, ни их вариации с другим хвостом названия "
            "(«яблочный пирог с корицей» — это тот же яблочный пирог; замени "
            "САМ ТИП пункта, а не формулировку):\n- "
            + "\n- ".join(context["avoid"])
        )
    # Только музыка. Запрет по трекам модель обходит следующим треком того же
    # артиста: у Agnes Obel три разных песни лежали в avoid одновременно,
    # и она всё равно стояла у 12 книг из 52. Поэтому исполнителей — целиком.
    if context.get("avoid_artists"):
        parts.append(
            "Эти исполнители уже примелькались в библиотеке — НЕ бери у них "
            "НИ ОДНОГО трека, даже если кажется, что именно этот подходит "
            "идеально. Запрет на исполнителя, а не на песню:\n- "
            + "\n- ".join(context["avoid_artists"])
        )
    return "\n\n".join(parts)



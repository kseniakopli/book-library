"""Пожелания читателя для рекомендаций (задача 114).

Замысел Ксении: дать человеку написать словами, чего он НЕ хочет и что любит
(«не люблю антиутопии, не предлагай»). Сейчас рекомендательные сервисы это
игнорируют, и наш игнорировал.

⚠ Главное здесь — не хранение, а то, что текст УЕЗЖАЕТ В ПРОМПТ. Значит это
канал влияния на модель, и относиться к нему надо как к чужому вводу:
ограничить длину, вычистить управляющие символы и подать так, чтобы модель
понимала — это данные, а не инструкции.

Полной защиты от подмены инструкций не существует: промпт и данные живут
в одном тексте. Но здесь и цена низкая — пользователь портит СВОИ же советы,
чужого не видит, платные вызовы держат лимиты частоты.
"""

import re

MAX_CHARS = 500          # несколько фраз; больше в промпте всё равно шум
MAX_LINES = 5

# Управляющие символы, кроме перевода строки: в тексте им делать нечего,
# а промпт они ломают незаметно (обрыв строки, склейка блоков).
_CONTROL = re.compile(r"[\x00-\x09\x0b-\x1f\x7f]")

# Строки, которыми обычно пробуют переписать инструкцию модели. Не «защита»
# в строгом смысле — мы просто не даём тексту притворяться служебным блоком
# нашего промпта.
#
# ⚠ Флаги задаются аргументом `re.compile`, а не инлайном `(?i)` внутри
# паттерна: Python разрешает глобальные флаги только в САМОМ начале выражения
# и падает с PatternError, если они встретились после первой альтернативы.
_INJECTION = re.compile(
    r"^\s*(system|assistant|user)\s*:|"
    r"\b(игнорируй|забудь)\s+(все\s+)?(предыдущие|прошлые)\s+(инструкции|указания)\b|"
    r"\bignore\s+(all\s+)?previous\s+instructions\b",
    re.IGNORECASE | re.MULTILINE,
)


def clean(raw: str | None) -> str | None:
    """Привести пожелания к виду, пригодному для промпта.

    Пусто (или осталось пусто после чистки) — None: «пожеланий нет» и «пустая
    строка» должны выглядеть в базе одинаково, иначе в промпт уедет пустой блок.
    """
    if not raw:
        return None

    text = _CONTROL.sub(" ", raw)
    text = _INJECTION.sub(" ", text)
    # схлопываем пробелы внутри строк, но абзацы сохраняем: человек их ставит
    lines = [" ".join(line.split()) for line in text.splitlines()]
    lines = [line for line in lines if line][:MAX_LINES]
    result = "\n".join(lines)[:MAX_CHARS].strip()
    return result or None

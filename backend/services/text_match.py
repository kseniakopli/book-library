"""Нечёткое сравнение названий — общее ядро (задача 126, 06.08).

Вынесено из `services/track_match.py`, когда та же механика понадобилась
для книг: совет модели надо сверять с ответом Google Books ровно так же,
как трек — с ответом Spotify. Копировать транслит и сравнение во второй
файл значило бы завести две правки там, где нужна одна (`Уроки.md` 4.2).

Здесь только ЧИСТЫЕ функции: ни сети, ни базы, ни ключей — поэтому модуль
тестируется без моков.

⚠ Нормализация у треков и книг РАЗНАЯ и остаётся в своих модулях:
у трека мешают приписки «- Remastered 2011» и «(feat. X)», у книги —
подзаголовок после двоеточия и пометки вроде «(сборник)». Общее здесь —
только транслит и способ мерить похожесть.
"""

from difflib import SequenceMatcher

# Кириллица → латиница. Нужна, потому что в зарубежных каталогах русское
# записывают транслитом: «Молчат Дома» → Molchat Doma (Spotify, инцидент
# 20.07), «Бенедетта Кристофани» → Benedetta Cristofani (Google Books).
# Без этого сравнение кириллицы с латиницей даёт нулевое сходство,
# и настоящая книга или трек выглядят выдумкой.
TRANSLIT = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
    "ж": "zh", "з": "z", "и": "i", "й": "i", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "kh", "ц": "ts", "ч": "ch", "ш": "sh", "щ": "shch",
    "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
}


def translit(text: str) -> str:
    return "".join(TRANSLIT.get(char, char) for char in text)


def similarity(first: str, second: str) -> float:
    """Похожесть двух УЖЕ нормализованных строк с учётом транслита:
    сравниваем как есть и обе в латинице, берём лучший результат."""
    return max(
        SequenceMatcher(None, first, second).ratio(),
        SequenceMatcher(None, translit(first), translit(second)).ratio(),
    )

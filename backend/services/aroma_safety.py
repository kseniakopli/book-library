    "ацетон", "растворител", "уайт-спирит", "толуол", "ксилол", "бензол",
    "хлорк", "хлорн", "отбеливател", "белизна",
    "нафталин", "формалин", "формальдегид",
    "аммиак", "нашатыр", "антифриз", "тормозн",
    # Добавлено 13.08 по замеру: в подборку приехал «стиральный порошок».

# --- Что отсекаем -----------------------------------------------------------
#
# Сравнение идёт по ОСНОВЕ слова внутри строки, поэтому «конопля», «конопли»
# и «семена конопли» ловятся одной записью. Основы намеренно длинные:
# короткая основа цепляет постороннее, а ложное срабатывание здесь дороже
# пропуска — оно молча выбрасывает нормальный аромат.

# 1. Подконтрольные вещества. Вопрос законности, и он не зависит от страны
#    читателя: географию мы намеренно не учитываем (решение Ксении 12.08).
CONTROLLED = (
    "конопл", "каннаб", "марихуан", "гашиш",
    "опиум", "опийн", "опия", "опий",
    "кокаин", "кока-лист", "лист коки",
    "аяуаск", "айяуаск",
    "сальвия дивинорум", "шалфей предсказател",
    "псилоциб", "мескалин", "пейот",
)

# 2. Бытовая химия, топливо, растворители. Вопрос здоровья.

"""Замер «до»: что лежит в сохранённых подборках ароматов (з.129, 12.08).

Скрипт НИЧЕГО не меняет. Он отвечает на один вопрос: какая доля уже
сгенерированных ароматов — выдуманные товары, которых нельзя купить.

⚠ Зачем замер, если баг уже понятен. Затем же, зачем он понадобился
рекомендациям 06.08: «модель выдумывает» и «мы плохо попросили» выглядят
на экране одинаково. Если после правки схемы доля выдумок упадёт с 60%
до 5% — правка сработала; если останется — дело не в порядке полей,
и внешнюю сверку (вариант А) придётся делать всерьёз, а не «потом».
Без цифры «до» этот вопрос неразрешим — сравнивать будет не с чем.

⛔ СМОТРЕТЬ НА ПРОДЕ. Ксения наполняет данные там, дев с ним расходится
(`Контекст_проекта.md`, раздел 5). Дев-замер ответит на другой вопрос.

Запуск локально из `backend/`:
    python scripts/aroma_audit.py

На проде (сначала посмотреть, потом верить):
    fly ssh console
    cd /app/backend && python scripts/aroma_audit.py

⚠ Что скрипт НЕ умеет. Он не знает, что продаётся в магазинах, — такого
источника у нас нет, ради этого всё и затевалось. Он лишь раскладывает
названия по признакам, которые видны из текста, и печатает СПИСОК, чтобы
человек посмотрел глазами. Это кандидаты, а не приговор: решает Ксения.
Тот же принцип, что в `docs_audit.py`.
"""

from __future__ import annotations

import json
import re
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from sqlmodel import Session, select  # noqa: E402

import database  # noqa: E402
from models import AISelection  # noqa: E402

# Сырьё пишут одним-двумя словами и строчными: «ветивер», «дубовый мох».
# Выдуманный товар почти всегда длиннее и с большой буквы — это название,
# а не вещество. Признак грубый и НАМЕРЕННО не строгий: он поднимает
# кандидатов на просмотр, а не выносит решение.
LOOKS_LIKE_A_PRODUCT = re.compile(r"^[А-ЯЁA-Z]")

# Слова, которыми называют форму выпуска. Если они есть в названии — это
# уже ближе к товару, чем к образу («свеча с полынью» купить можно).
FORM_WORDS = (
    "масло", "свеч", "благовон", "аромапалочк", "палочк", "трав",
    "смол", "гидролат", "саше", "специ", "ладан",
)


def classify(title: str) -> str:
    """Грубая раскладка названия по корзинам.

    Разделяет всего два признака: сколько слов и с какой буквы начинается.
    Сырьё — короткое и по сути («ветивер», «дубовый мох»); выдуманный
    товар — длинное и с заглавной, потому что это ИМЯ («Крахмальный
    воротничок»). Больше признаков брать нет смысла: точности это
    не добавит, а иллюзию точности создаст.
    """
    if not title:
        return "непонятно"
    words = title.split()
    low = title.lower()
    if any(w in low for w in FORM_WORDS):
        return "названа форма"          # «эфирное масло ветивера», «ладан»
    if len(words) == 1:
        return "похоже на сырьё"        # «ветивер», «Сандал»
    if not LOOKS_LIKE_A_PRODUCT.match(title):
        return "похоже на сырьё"        # «дубовый мох»
    return "похоже на выдумку"          # «Крахмальный воротничок»


def main() -> None:
    database.init_db()
    with Session(database.engine) as session:
        rows = session.exec(
            select(AISelection).where(AISelection.category == "aroma")
        ).all()

    if not rows:
        # Пустой результат обязан означать «чисто», а не «не смог посмотреть»
        # (правило из morning_check.py). Здесь он значит «нечего смотреть».
        print("Подборок ароматов в базе нет — замерять нечего.")
        return

    buckets: Counter[str] = Counter()
    suspects: list[tuple[str, str]] = []
    materials: Counter[str] = Counter()
    forms: Counter[str] = Counter()
    already_new = 0
    total = 0

    for row in rows:
        try:
            items = json.loads(row.payload)
        except (TypeError, ValueError):
            continue
        for item in items:
            if not isinstance(item, dict):
                continue
            total += 1
            if item.get("material"):
                already_new += 1          # подборка уже нового вида
                materials[item["material"]] += 1
                forms[item.get("form") or "—"] += 1
                continue
            title = (item.get("title") or "").strip()
            bucket = classify(title)
            buckets[bucket] += 1
            if bucket == "похоже на выдумку":
                suspects.append((title, row.source))

    print(f"Подборок ароматов: {len(rows)}, пунктов в них: {total}")
    print(f"Уже в новом виде (есть material): {already_new}")

    # --- Замер «ПОСЛЕ»: сырьё из новых подборок -------------------------
    #
    # ⚠ Машина не знает, продаётся ли «лабданум», — источника у нас нет,
    # ради этого всё и затевалось. Поэтому здесь не оценка, а СПИСОК:
    # десяток названий Ксения проверит быстрее, чем мы напишем проверку.
    # Смотреть надо именно на новые пункты — эффект правки меряют
    # по новым объектам, иначе он растворится в старых (`Уроки.md` 1.8).
    if materials:
        print(f"\nСырьё в новых подборках — {len(materials)} разных названий:")
        for name, n in materials.most_common():
            print(f"  {n:3}×  {name}")
        print("\nФормы выпуска:")
        for name, n in forms.most_common():
            print(f"  {n:3}×  {name}")
        print(
            "\n⚠ Пройди по списку глазами: каждое ли название можно"
            "\n   набрать в поиске магазина и что-то найти? Если да —"
            "\n   правка сработала и з.131 (сверка с маркетплейсом) не нужна."
            "\n   Однообразие тоже смотри: если на 10 книг сырьё повторяется"
            "\n   пять раз, это mode collapse (`Уроки.md` 1.9), лечится не так."
        )

    old = total - already_new
    if not old:
        print("\nСтарых пунктов не осталось — сравнивать не с чем.")
        return

    print(f"\nСтарых пунктов: {old}")
    for name, n in buckets.most_common():
        print(f"  {name:20} {n:4}  ({n * 100 // old}%)")

    print("\nКандидаты в выдумки — смотреть глазами:")
    for name, source in sorted(set(suspects))[:40]:
        print(f"  · {name}   [{source}]")
    if len(set(suspects)) > 40:
        print(f"  … ещё {len(set(suspects)) - 40}")

    print(
        "\n⚠ Это КАНДИДАТЫ по формальному признаку, а не факт."
        "\n   «Дубовый мох» сюда попадёт, хотя это настоящее сырьё."
        "\n   Цифра нужна как точка отсчёта: тот же скрипт после"
        "\n   перегенерации покажет, сработала ли правка схемы."
    )


if __name__ == "__main__":
    main()

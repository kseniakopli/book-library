// Склонение существительных после числа.
// Вынесено из AuthorsPage (задача 112): то же нужно списку жанров, а копия
// правила в двух местах — это одна правка и будущее расхождение.

/** «1 книга» / «2 книги» / «5 книг» — без склонения число выглядит машинным. */
export function booksLabel(n) {
  const tens = n % 100;
  const ones = n % 10;
  // 11–14 — исключение: «11 книг», хотя ones попадает в 1–4
  if (tens >= 11 && tens <= 14) return `${n} книг`;
  if (ones === 1) return `${n} книга`;
  if (ones >= 2 && ones <= 4) return `${n} книги`;
  return `${n} книг`;
}
